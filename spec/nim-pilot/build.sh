#!/bin/sh
# build.sh: the Nim pilot's binaries, in build/ (nothing outside this folder is written).
#   build/c/bench-TC-{timing,memory}        C Control: tcm.c with the m4 gcd, m4_libconf.py's exact command lines
#   build/nim/bench-TCnim-{timing,memory}   the Nim port (tcm.nim) linked with the same unchanged driver bench_m4.c
#   build/nimexc/bench-TCnim-timing         variant: without --panics:on (Nim's default goto exceptions), to show their cost
#   build/nim3/bench-TCnim-timing           variant: Nim's own -d:danger default optimisation (gcc -O3)
#   build/nimif/bench-TCnim-timing          variant: -d:nimIfSelect, Nim's `if` expressions in place of C's `?:`
# Usage: NIM=/path/to/nim sh build.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SPEC=$(cd "$HERE/.." && pwd)
NIM=${NIM:-nim}
B=$HERE/build
CFLAGS="-std=c11 -Wall -Wextra -Werror -O2"
INC="-I $SPEC/lib/include -I $SPEC/lib/vendor08/m4 -I $SPEC/lib/vendor08 -I $SPEC/lib/src -I $SPEC/lib/tests -I $SPEC/test"
# Nim: C backend, a static library with no main; danger (no bounds, range, overflow, nil checks: overflow is the
# port's own explicit checks); ARC (no GC; the port allocates nothing through Nim anyway); Nim's allocator replaced
# by malloc; panics on, so that no call carries the goto-exceptions error test
NIMFLAGS="--hints:off --app:staticlib --noMain -d:danger --mm:arc -d:useMalloc --cc:gcc"
WRAP="-Wl,--wrap=malloc,--wrap=calloc,--wrap=realloc,--wrap=free"

for build in timing memory; do
    case $build in timing) D="";; memory) D="-DM2_MEM";; esac
    O=$B/obj/$build
    mkdir -p "$O" "$B/c" "$B/nim"
    # the shared objects, as m4_libconf.py compiles them
    gcc $CFLAGS $D $INC -c "$SPEC/lib/src/tcm.c" -o "$O/tcm.o"
    gcc $CFLAGS $D $INC -c "$SPEC/lib/vendor08/common.c" -o "$O/common.o"
    for m in m1common m2common m3common; do gcc $CFLAGS $D $INC -c "$SPEC/lib/src/$m.c" -o "$O/$m.o"; done
    L=""; [ $build = memory ] && L=$WRAP
    COMMON="$O/common.o $O/m1common.o $O/m2common.o $O/m3common.o"
    gcc $CFLAGS $D -DIMPL_TC $INC "$SPEC/test/bench_m4.c" "$O/tcm.o" $COMMON $L -o "$B/c/bench-TC-$build"
    # the Nim port: C code generated by Nim, compiled by the same gcc at -O2 (C's level), linked with the same driver
    "$NIM" c $NIMFLAGS --panics:on "--gcc.options.speed=-O2 -fno-strict-aliasing -fno-ident" \
        "--passC:-I$SPEC/lib/include -I$SPEC/lib/vendor08" \
        "--nimcache:$B/nimcache-$build" "-o:$B/nim/libtcmnim-$build.a" "$HERE/tcm.nim"
    gcc $CFLAGS $D -DIMPL_TC $INC "$SPEC/test/bench_m4.c" "$B/nim/libtcmnim-$build.a" $COMMON $L -o "$B/nim/bench-TCnim-$build"
done
# the two variants, timing build only
O=$B/obj/timing
COMMON="$O/common.o $O/m1common.o $O/m2common.o $O/m3common.o"
mkdir -p "$B/nimexc" "$B/nim3"
"$NIM" c $NIMFLAGS "--gcc.options.speed=-O2 -fno-strict-aliasing -fno-ident" \
    "--passC:-I$SPEC/lib/include -I$SPEC/lib/vendor08" "--nimcache:$B/nimcache-exc" "-o:$B/nimexc/libtcmnim.a" "$HERE/tcm.nim"
gcc $CFLAGS -DIMPL_TC $INC "$SPEC/test/bench_m4.c" "$B/nimexc/libtcmnim.a" $COMMON -o "$B/nimexc/bench-TCnim-timing"
"$NIM" c $NIMFLAGS --panics:on \
    "--passC:-I$SPEC/lib/include -I$SPEC/lib/vendor08" "--nimcache:$B/nimcache-O3" "-o:$B/nim3/libtcmnim.a" "$HERE/tcm.nim"
gcc $CFLAGS -DIMPL_TC $INC "$SPEC/test/bench_m4.c" "$B/nim3/libtcmnim.a" $COMMON -o "$B/nim3/bench-TCnim-timing"
mkdir -p "$B/nimif"
"$NIM" c $NIMFLAGS --panics:on -d:nimIfSelect "--gcc.options.speed=-O2 -fno-strict-aliasing -fno-ident" \
    "--passC:-I$SPEC/lib/include -I$SPEC/lib/vendor08" "--nimcache:$B/nimcache-if" "-o:$B/nimif/libtcmnim.a" "$HERE/tcm.nim"
gcc $CFLAGS -DIMPL_TC $INC "$SPEC/test/bench_m4.c" "$B/nimif/libtcmnim.a" $COMMON -o "$B/nimif/bench-TCnim-timing"
echo built
