"""Writes cbench/oct_table.h: the octonion product, written out term by term from the Cayley-Dickson table in
family.py, so that every implementation in oct.c compiles the same constant signs."""
from pathlib import Path

import family as FA

OUT = Path(__file__).resolve().parent.parent / "cbench" / "oct_table.h"


def terms():
    """For each result axis, the eight (sign, x, y) with e_x e_y = sign e_axis."""
    by = {z: [] for z in range(8)}
    for x in range(8):
        for y in range(8):
            s, z = FA.basis_mul(x, y, 8)
            by[z].append((s, x, y))
    return by


def main():
    by = terms()
    lines = ["/* generated by build/gen_oct_table.py from family.basis_mul: do not edit */",
             "static const int OAXIS[8][8] = {" + ", ".join(
                 "{" + ", ".join(str(FA.basis_mul(x, y, 8)[1]) for y in range(8)) + "}" for x in range(8)) + "};",
             "static const int OSIGN[8][8] = {" + ", ".join(
                 "{" + ", ".join(str(FA.basis_mul(x, y, 8)[0]) for y in range(8)) + "}" for x in range(8)) + "};",
             "/* r[z] = sum of sign * x[a] * y[b], with T the accumulator type */",
             "#define OCTMUL(T, X, Y, R) do { \\"]
    for z in range(8):
        e = " ".join(("+ " if s > 0 else "- ") + f"(T)(X(%d)) * (Y(%d))" % (a, b) for s, a, b in by[z])
        lines.append(f"    R({z}) = {e[2:] if e.startswith('+') else e}; \\")
    lines.append("} while (0)")
    lines.append("/* the same with library calls: MUL(r, x, y); then ADDMUL/SUBMUL(r, x, y) */")
    lines.append("#define OCTLIB(MUL, ADDMUL, SUBMUL, X, Y, R) do { \\")
    for z in range(8):
        (s0, a0, b0), *rest = by[z]
        assert s0 == 1
        parts = [f"MUL(R({z}), X({a0}), Y({b0}));"] + [
            f"{'ADDMUL' if s > 0 else 'SUBMUL'}(R({z}), X({a}), Y({b}));" for s, a, b in rest]
        lines.append("    " + " ".join(parts) + " \\")
    lines.append("} while (0)")
    lines.append("/* checked int64, written out the same way: O |= 1 on any overflow */")
    lines.append("#define OCTCHK(X, Y, R, O) do { int64_t acc_, t_; \\")
    for z in range(8):
        (s0, a0, b0), *rest = by[z]
        parts = [f"O |= __builtin_mul_overflow(X({a0}), Y({b0}), &acc_);"]
        for s_, a, b in rest:
            parts.append(f"O |= __builtin_mul_overflow(X({a}), Y({b}), &t_); "
                         f"O |= __builtin_{'add' if s_ > 0 else 'sub'}_overflow(acc_, t_, &acc_);")
        parts.append(f"R({z}) = acc_;")
        lines.append("    " + " ".join(parts) + " \\")
    lines.append("} while (0)")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
