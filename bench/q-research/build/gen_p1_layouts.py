"""Phase one, scalar layouts: the layout parameters, and cbench/p1_layouts.h, which instantiates one specialised C
decoder and encoder per layout so that every layout gets the same quality of code.

Layouts (A x B x C in the variants register):
  tfit   header byte + word, unit bits fitted to the algebra (complex here: 2 unit bits)
  tuni   header byte + word, the uniform (octonion) header: 4 unit bits
  pfit   packed power of two, unit bits fitted (complex: 2)
  puni   packed power of two, uniform: 4 unit bits
each with the slash bits at the top (after the unit) or at the bottom of the value.

Read as one bit string from the top, a value is
  tuple, top:     unit | header slash | borrowed slash | numerator | denominator - 1
  tuple, bottom:  unit | header slash || numerator | denominator - 1 | borrowed slash
  packed, top:    unit | slash | numerator | denominator - 1
  packed, bottom: unit | numerator | denominator - 1 | slash
The numerator occupies the top s + 1 data bits, s being the slash value; denominators are stored minus one.
"""
from pathlib import Path

import family as FA

OUT = Path(__file__).resolve().parent.parent / "cbench" / "p1_layouts.h"
WORDS = (16, 32, 64, 128)
DIMS = {"fit": 2, "uni": 8}          # complex numbers as the fitted example; the uniform header is the same for all


def tuple_layout(dim, word):
    U, h, b, D = FA.layout(dim, word, 8)
    return dict(U=U, h=h, b=b, D=D, total=8 + word, word=word)


def packed_layout(dim, width):
    U = FA.unit_bits(dim)
    k = 1
    while (1 << k) < width - U - k:          # k slash bits must address D = width - U - k positions
        k += 1
    return dict(U=U, k=k, D=width - U - k, total=width, word=width)


def layouts():
    out = []
    for kind in ("t", "p"):
        for hdr, dim in DIMS.items():
            for order in ("top", "bot"):
                for w in WORDS:
                    lay = tuple_layout(dim, w) if kind == "t" else packed_layout(dim, w)
                    lay.update(name=f"{kind}{hdr}_{order}_{w}", kind=kind, hdr=hdr, dim=dim, order=order)
                    out.append(lay)
    return out


def ctype(w):
    return {16: "uint16_t", 32: "uint32_t", 64: "uint64_t", 128: "u128"}[w]


def main():
    lines = ["/* generated by build/gen_p1_layouts.py: one decoder and encoder per layout, constants inlined */"]
    names = []
    for L in layouts():
        n, T = L["name"], ctype(L["word"])
        top = 1 if L["order"] == "top" else 0
        if L["kind"] == "t":
            lines.append(f"TUPLE({n}, {T}, {L['word']}, {L['U']}, {L['h']}, {L['b']}, {L['D']}, {top})")
        else:
            lines.append(f"PACKED({n}, {T}, {L['word']}, {L['U']}, {L['k']}, {L['D']}, {top})")
        names.append(n)
    lines.append("#define ALL_LAYOUTS(X) " + " ".join(f"X({n})" for n in names))
    OUT.write_text("\n".join(lines) + "\n")


def ref_decode(L, header, value):
    """Reference decoder in Python for any layout here: (sign, axis, p, q); zero is (1, 0, 0, 1)."""
    U, D = L["U"], L["D"]
    if L["kind"] == "t":
        h, b, w = L["h"], L["b"], L["word"]
        code = header >> h
        if L["order"] == "top":
            s = ((header & ((1 << h) - 1)) << b) | (value >> D)
            data = value & ((1 << D) - 1)
        else:
            s = ((header & ((1 << h) - 1)) << b) | (value & ((1 << b) - 1))
            data = value >> b
    else:
        k, w = L["k"], L["word"]
        code = value >> (w - U)
        if L["order"] == "top":
            s = (value >> D) & ((1 << k) - 1)
            data = value & ((1 << D) - 1)
        else:
            s = value & ((1 << k) - 1)
            data = (value >> k) & ((1 << D) - 1)
    sign = -1 if (code >> (U - 1)) & 1 else 1
    axis = code & ((1 << (U - 1)) - 1)
    s = min(s, D - 1)
    width = D - (s + 1)
    p = data >> width
    q = (data & ((1 << width) - 1)) + 1
    if p == 0:
        return 1, 0, 0, 1
    return sign, axis, p, q


def ref_encode(L, sign, axis, p, q):
    """(header, value) for tuples, (0, value) for packed; None if p/q does not fit."""
    U, D = L["U"], L["D"]
    if p == 0:
        return 0, 0
    if p.bit_length() + (q - 1).bit_length() > D:
        return None
    code = ((1 if sign < 0 else 0) << (U - 1)) | axis
    s = p.bit_length() - 1
    data = (p << (D - (s + 1))) | (q - 1)
    if L["kind"] == "t":
        h, b = L["h"], L["b"]
        hs, bs = s >> b, s & ((1 << b) - 1)
        header = (code << h) | hs
        value = (bs << D) | data if L["order"] == "top" else (data << b) | bs
        return header, value
    k, w = L["k"], L["word"]
    value = (code << (w - U)) | ((s << D) | data if L["order"] == "top" else (data << k) | s)
    return 0, value


if __name__ == "__main__":
    main()
    for L in layouts():
        print(L["name"], {k: L[k] for k in ("U", "D", "total")})
